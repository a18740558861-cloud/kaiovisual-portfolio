function findProjectById(id) {
  for (const sec of [SITE.space, SITE.plane]) {
    for (const mod of sec.modules) {
      const p = mod.projects.find(x => x.id === id);
      if (p) return { section: sec.title, module: mod.name, project: p };
    }
  }
  return null;
}
